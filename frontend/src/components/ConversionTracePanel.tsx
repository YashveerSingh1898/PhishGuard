import React, { useState } from 'react';
import { ChevronLeft, ChevronRight, Layers, ArrowRight, BookOpen } from 'lucide-react';
import { SubsetTraceStep, MinimizationStep, InitialPartition } from '../types';

interface ConversionTracePanelProps {
  subsetTrace: SubsetTraceStep[];
  minimizationSteps: MinimizationStep[];
  initialPartitions: InitialPartition[];
}

export const ConversionTracePanel: React.FC<ConversionTracePanelProps> = ({
  subsetTrace,
  minimizationSteps,
  initialPartitions,
}) => {
  const [activeTraceType, setActiveTraceType] = useState<'subset' | 'minimization'>('subset');
  const [subsetIndex, setSubsetIndex] = useState<number>(0);
  const [minIndex, setMinIndex] = useState<number>(0);

  // Bounds checks
  const currentSubsetStep = subsetTrace[subsetIndex];
  const currentMinStep = minimizationSteps[minIndex];

  return (
    <div className="rounded-xl border border-navy-800 bg-navy-900/50 p-5 shadow-lg">
      {/* Header and Switcher */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 mb-4 pb-3 border-b border-navy-800">
        <div>
          <h3 className="text-base font-semibold text-white flex items-center gap-2">
            <BookOpen className="w-4 h-4 text-teal-400" />
            <span>Interactive Conversion Trace</span>
          </h3>
          <p className="text-xs text-slate-400 mt-0.5">
            Step-by-step mathematical trace generated by the backend transformation engine.
          </p>
        </div>

        {/* Tab toggle */}
        <div className="flex rounded-lg bg-navy-950 p-1 border border-navy-800">
          <button
            type="button"
            onClick={() => setActiveTraceType('subset')}
            className={`px-3 py-1 rounded text-xs font-mono transition-all ${
              activeTraceType === 'subset'
                ? 'bg-teal-500/20 text-teal-300 font-semibold'
                : 'text-slate-400 hover:text-white'
            }`}
          >
            Subset Construction ({subsetTrace.length} Steps)
          </button>
          <button
            type="button"
            onClick={() => setActiveTraceType('minimization')}
            className={`px-3 py-1 rounded text-xs font-mono transition-all ${
              activeTraceType === 'minimization'
                ? 'bg-teal-500/20 text-teal-300 font-semibold'
                : 'text-slate-400 hover:text-white'
            }`}
          >
            Partition Refinement ({minimizationSteps.length} Steps)
          </button>
        </div>
      </div>

      {/* --- View 1: Subset Construction Trace --- */}
      {activeTraceType === 'subset' && (
        <div>
          {subsetTrace.length === 0 ? (
            <div className="py-8 text-center text-slate-500 text-xs font-mono">
              No subset trace steps generated for this automaton.
            </div>
          ) : (
            <div>
              {/* Stepper controls */}
              <div className="flex items-center justify-between mb-4">
                <span className="text-xs font-mono text-slate-400">
                  Step <strong className="text-teal-400">{subsetIndex + 1}</strong> of{' '}
                  <strong className="text-white">{subsetTrace.length}</strong>
                </span>

                <div className="flex items-center space-x-2">
                  <button
                    type="button"
                    onClick={() => setSubsetIndex((prev) => Math.max(0, prev - 1))}
                    disabled={subsetIndex === 0}
                    className="p-1.5 rounded bg-navy-850 hover:bg-navy-800 disabled:opacity-40 disabled:cursor-not-allowed text-slate-300 hover:text-white border border-navy-750 transition-colors"
                    aria-label="Previous step"
                  >
                    <ChevronLeft className="w-4 h-4" />
                  </button>
                  <button
                    type="button"
                    onClick={() => setSubsetIndex((prev) => Math.min(subsetTrace.length - 1, prev + 1))}
                    disabled={subsetIndex === subsetTrace.length - 1}
                    className="p-1.5 rounded bg-navy-850 hover:bg-navy-800 disabled:opacity-40 disabled:cursor-not-allowed text-slate-300 hover:text-white border border-navy-750 transition-colors"
                    aria-label="Next step"
                  >
                    <ChevronRight className="w-4 h-4" />
                  </button>
                </div>
              </div>

              {/* Trace Card */}
              {currentSubsetStep && (
                <div className="p-4 rounded-lg bg-navy-950 border border-navy-800 font-mono text-xs">
                  <div className="flex flex-wrap items-center gap-3 mb-3">
                    {/* Source subset */}
                    <div className="p-2.5 rounded bg-navy-900 border border-navy-800 flex-1 min-w-[140px]">
                      <div className="text-[10px] text-slate-500 uppercase tracking-wider font-semibold">
                        Source DFA State
                      </div>
                      <div className="text-teal-300 font-bold text-sm mt-0.5">
                        {currentSubsetStep.source}
                      </div>
                      <div className="text-[11px] text-slate-400 mt-1">
                        Subset: &#123;{currentSubsetStep.source_subset.map((s) => `S${s}`).join(', ')}&#125;
                      </div>
                    </div>

                    {/* Transition Symbol */}
                    <div className="flex flex-col items-center px-3 py-1 bg-navy-850 rounded border border-navy-750">
                      <span className="text-[10px] text-slate-500 uppercase">Input</span>
                      <span className="text-white font-bold text-base my-0.5">
                        '{currentSubsetStep.symbol}'
                      </span>
                      <ArrowRight className="w-3.5 h-3.5 text-teal-400" />
                    </div>

                    {/* Target subset */}
                    <div className="p-2.5 rounded bg-navy-900 border border-navy-800 flex-1 min-w-[140px]">
                      <div className="text-[10px] text-slate-500 uppercase tracking-wider font-semibold">
                        Destination DFA State
                      </div>
                      <div className="text-teal-300 font-bold text-sm mt-0.5">
                        {currentSubsetStep.target}
                      </div>
                      <div className="text-[11px] text-slate-400 mt-1">
                        Subset: &#123;{currentSubsetStep.target_subset.map((s) => `S${s}`).join(', ')}&#125;
                      </div>
                    </div>
                  </div>

                  {/* Backend Explanation */}
                  <div className="p-3 rounded bg-navy-900/60 border border-navy-800/80 text-slate-300 text-xs leading-relaxed">
                    <span className="text-teal-400 font-semibold mr-1.5">Algorithmic Step:</span>
                    {currentSubsetStep.explanation}
                  </div>
                </div>
              )}

              {/* Progress Slider / Quick Jump */}
              <div className="mt-4 flex items-center gap-2">
                <input
                  type="range"
                  min="0"
                  max={Math.max(0, subsetTrace.length - 1)}
                  value={subsetIndex}
                  onChange={(e) => setSubsetIndex(parseInt(e.target.value, 10))}
                  className="w-full h-1.5 bg-navy-800 rounded-lg appearance-none cursor-pointer accent-teal-400"
                />
              </div>
            </div>
          )}
        </div>
      )}

      {/* --- View 2: DFA Minimization (Partition Refinement) --- */}
      {activeTraceType === 'minimization' && (
        <div>
          {minimizationSteps.length === 0 ? (
            <div className="py-8 text-center text-slate-500 text-xs font-mono">
              No minimization steps recorded.
            </div>
          ) : (
            <div>
              {/* Stepper controls */}
              <div className="flex items-center justify-between mb-4">
                <span className="text-xs font-mono text-slate-400">
                  Refinement Iteration <strong className="text-teal-400">{minIndex + 1}</strong> of{' '}
                  <strong className="text-white">{minimizationSteps.length}</strong>
                </span>

                <div className="flex items-center space-x-2">
                  <button
                    type="button"
                    onClick={() => setMinIndex((prev) => Math.max(0, prev - 1))}
                    disabled={minIndex === 0}
                    className="p-1.5 rounded bg-navy-850 hover:bg-navy-800 disabled:opacity-40 disabled:cursor-not-allowed text-slate-300 hover:text-white border border-navy-750 transition-colors"
                    aria-label="Previous step"
                  >
                    <ChevronLeft className="w-4 h-4" />
                  </button>
                  <button
                    type="button"
                    onClick={() => setMinIndex((prev) => Math.min(minimizationSteps.length - 1, prev + 1))}
                    disabled={minIndex === minimizationSteps.length - 1}
                    className="p-1.5 rounded bg-navy-850 hover:bg-navy-800 disabled:opacity-40 disabled:cursor-not-allowed text-slate-300 hover:text-white border border-navy-750 transition-colors"
                    aria-label="Next step"
                  >
                    <ChevronRight className="w-4 h-4" />
                  </button>
                </div>
              </div>

              {/* Step Card */}
              {currentMinStep && (
                <div className="p-4 rounded-lg bg-navy-950 border border-navy-800 font-mono text-xs">
                  <div className="mb-3 flex items-center justify-between">
                    <span className="text-slate-400">
                      Step #{currentMinStep.step}:{' '}
                      <strong className="text-teal-300">{currentMinStep.partition_count} Partition Block(s)</strong>
                    </span>
                    <span className="px-2 py-0.5 rounded bg-navy-900 text-teal-400 text-[10px] border border-navy-800">
                      Equivalence Classes
                    </span>
                  </div>

                  <p className="text-slate-300 text-xs mb-3 leading-relaxed">
                    {currentMinStep.description}
                  </p>

                  {/* Partition Blocks Render */}
                  <div className="space-y-2">
                    <div className="text-[11px] font-semibold text-slate-400 flex items-center gap-1.5">
                      <Layers className="w-3.5 h-3.5 text-teal-400" />
                      <span>Current Partition State:</span>
                    </div>
                    <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-2">
                      {currentMinStep.partitions.map((block, bIdx) => (
                        <div
                          key={bIdx}
                          className="p-2.5 rounded bg-navy-900 border border-navy-800 flex flex-col justify-between"
                        >
                          <span className="text-[10px] text-teal-400 font-bold mb-1">
                            Block P{bIdx} ({block.length} state{block.length > 1 ? 's' : ''}):
                          </span>
                          <span className="text-white text-xs font-bold">
                            &#123;{block.join(', ')}&#125;
                          </span>
                        </div>
                      ))}
                    </div>
                  </div>
                </div>
              )}

              {/* Initial Partition Context */}
              {initialPartitions && initialPartitions.length > 0 && (
                <div className="mt-3 p-3 rounded bg-navy-950/70 border border-navy-850 text-[11px] font-mono text-slate-400">
                  <span className="text-teal-400 font-semibold mr-1">Initial Separation:</span>
                  {initialPartitions.map((p, idx) => (
                    <span key={idx} className="mr-3">
                      P{p.partition_index} ({p.group_type}): &#123;{p.states.join(', ')}&#125;
                    </span>
                  ))}
                </div>
              )}
            </div>
          )}
        </div>
      )}
    </div>
  );
};
